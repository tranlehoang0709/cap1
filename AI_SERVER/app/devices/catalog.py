# Registry is immutable at runtime; new diagram profiles are additive entries.
DEVICE_PROFILES = MappingProxyType(_PROFILES)


def list_device_profiles() -> tuple[DeviceProfile, ...]:
    return tuple(DEVICE_PROFILES[key] for key in sorted(DEVICE_PROFILES))


def get_device_profile(profile_id: str) -> DeviceProfile | None:
    return DEVICE_PROFILES.get(profile_id)
