#include <esp_log.h>
#include <esp_err.h>
#include <nvs.h>
#include <nvs_flash.h>
#include <driver/gpio.h>
#include <esp_event.h>
#include <freertos/FreeRTOS.h>
#include <freertos/task.h>

#include "application.h"

#define TAG "main"

extern "C" void app_main(void)
{
#if defined(CONFIG_AIVA_LAN_BOOTSTRAP) && CONFIG_AIVA_LAN_BOOTSTRAP
    // HttpClient's debug trace contains request headers. Device proof is sent
    // only over TLS and this component's header trace stays disabled.
    esp_log_level_set("HttpClient", ESP_LOG_WARN);
#endif
    // Initialize NVS flash for WiFi configuration
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_LOGE(TAG, "NVS requires approved recovery; preserving stored data");
    }
    ESP_ERROR_CHECK(ret);

    // Initialize and run the application
    auto& app = Application::GetInstance();
    app.Initialize();
    app.Run();  // This function runs the main event loop and never returns
}
